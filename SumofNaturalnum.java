public class SumofNaturalnum {
    public static void main(String[] args) {
        System.out.println("Sum of natural numbers from 1 to 50:");
        int sum = 0;
        for (int i = 1; i <= 50; i++) {
            sum += i;
        }
        System.out.println("The sum is " + sum);
        System.out.println("Develop by Prajwal Chapagain");
    }

}
