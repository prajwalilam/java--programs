public class Swaps {
    public static void main(String[] args ){
        int a =50;
        int b = 100;
        System.out.println("Before swaping:");
        System.out.println("a = " + a + " and b = " + b);
        int temp;
        temp =a;
        a = b;
        b = temp;
        System.out.println("After swaping: a = " + a + " and b = " + b );
        System.out.println("Developed by  Prajwal Chapagain");
        

    }
    
}
